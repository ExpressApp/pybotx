FSM_STATE_REPO_TEMPLATE = Template(
    """from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
import importlib
import json
from types import SimpleNamespace
from typing import Any

from pybotx_fsm.fsm import FSMStateData
from redis.asyncio import Redis


@dataclass(frozen=True, slots=True)
class RedisFSMStateRepo:
    redis: Redis
    default_expire_seconds: int = 900
    key_prefix: str = "pybotx:fsm"

    def __post_init__(self) -> None:
        if self.default_expire_seconds <= 0:
            raise ValueError("FSM state TTL should be greater than 0")
        if not self.key_prefix:
            raise ValueError("FSM state key prefix should not be empty")

    async def get(self, key: Any, default: Any = None) -> Any:
        payload = await self.redis.get(self._build_redis_key(key))
        if payload is None:
            return default

        parsed_payload = json.loads(payload)
        enum_cls = self._load_enum_class(
            module_name=parsed_payload["state_module"],
            qualname=parsed_payload["state_qualname"],
        )
        state = enum_cls[parsed_payload["state_name"]]
        storage = SimpleNamespace(**parsed_payload["storage"])
        return FSMStateData(state=state, storage=storage)

    async def set(
        self,
        key: Any,
        value: Any,
        expire: int | None = None,
    ) -> None:
        if not isinstance(value, FSMStateData):
            raise TypeError("RedisFSMStateRepo expects FSMStateData values")
        if not isinstance(value.state, Enum):
            raise TypeError("FSM state should be an Enum member")

        storage = vars(value.storage)
        payload = json.dumps(
            {
                "state_module": value.state.__class__.__module__,
                "state_qualname": value.state.__class__.__qualname__,
                "state_name": value.state.name,
                "storage": storage,
            },
            ensure_ascii=True,
            sort_keys=True,
        )
        await self.redis.set(
            self._build_redis_key(key),
            payload,
            ex=expire or self.default_expire_seconds,
        )

    async def delete(self, key: Any) -> None:
        await self.redis.delete(self._build_redis_key(key))

    def _build_redis_key(self, key: Any) -> str:
        return f"{self.key_prefix}:{key}"

    def _load_enum_class(self, *, module_name: str, qualname: str) -> type[Enum]:
        module = importlib.import_module(module_name)
        target: Any = module
        for part in qualname.split("."):
            target = getattr(target, part)

        if not isinstance(target, type) or not issubclass(target, Enum):
            raise TypeError(
                f"Stored FSM state class `{module_name}:{qualname}` is not an Enum",
            )

        return target
"""
)


