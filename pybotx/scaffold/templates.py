ARCHITECTURE_TEST_TEMPLATE = Template(
    """from __future__ import annotations

import ast
from pathlib import Path


PACKAGE_ROOT = Path(__file__).resolve().parents[1] / "src" / "$package_name"
PACKAGE_PREFIX = "$package_name"

FORBIDDEN_LAYER_IMPORTS = {
    "domain": (
        f"{PACKAGE_PREFIX}.application",
        f"{PACKAGE_PREFIX}.infrastructure",
        f"{PACKAGE_PREFIX}.presentation",
    ),
    "application": (
        f"{PACKAGE_PREFIX}.infrastructure",
        f"{PACKAGE_PREFIX}.presentation",
    ),
    "infrastructure": (
        f"{PACKAGE_PREFIX}.presentation",
    ),
}

FORBIDDEN_EXTERNAL_IMPORTS = {
    "domain": (
        "pybotx",
        "fastapi",
        "redis",
        "dependency_injector",
        "pydantic_settings",
    ),
    "application": (
        "pybotx",
        "fastapi",
        "redis",
        "dependency_injector",
        "pydantic_settings",
    ),
}


def _iter_imported_modules(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    imported_modules: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported_modules.extend(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            if node.level != 0 or node.module is None:
                continue
            imported_modules.append(node.module)
    return imported_modules


def _iter_layer_files(layer: str) -> list[Path]:
    return sorted((PACKAGE_ROOT / layer).rglob("*.py"))


def test_layer_boundaries() -> None:
    for layer, forbidden_prefixes in FORBIDDEN_LAYER_IMPORTS.items():
        for path in _iter_layer_files(layer):
            imported_modules = _iter_imported_modules(path)
            for module_name in imported_modules:
                assert not module_name.startswith(forbidden_prefixes), (
                    f"{path} imports outer layer module {module_name}"
                )


def test_framework_imports_are_kept_out_of_inner_layers() -> None:
    for layer, forbidden_prefixes in FORBIDDEN_EXTERNAL_IMPORTS.items():
        for path in _iter_layer_files(layer):
            imported_modules = _iter_imported_modules(path)
            for module_name in imported_modules:
                assert not module_name.startswith(forbidden_prefixes), (
                    f"{path} imports framework module {module_name}"
                )
"""
)


